def check_external_tools():
    """Check for external dependencies (Whisper.cpp, Ollama)."""
    print_step("External tools check")

    tools = {
        "Ollama": {
            "cmd": ["ollama", "--version"] if os.name != "nt" else ["ollama.exe", "--version"],
            "url": "https://ollama.com/download",
            "optional": True,
        },
        "Whisper.cpp": {
            "cmd": ["whisper-cli"] if os.name != "nt" else ["whisper-cli.exe"],
            "url": "https://github.com/ggerganov/whisper.cpp",
            "optional": True,
        },
    }

    for name, info in tools.items():
        try:
            result = subprocess.run(
                info["cmd"], capture_output=True, text=True, timeout=10,
            )
            if result.returncode == 0 or result.returncode == 1:  # some tools return 1 for --version
                print(f"  ✅ {name} found")
            else:
                raise FileNotFoundError
        except (FileNotFoundError, subprocess.TimeoutExpired):
            if info["optional"]:
                print(f"  ⚠️  {name} not found (optional)")
                print(f"     Get it at: {info['url']}")
            else:
                print(f"  ❌ {name} not found. Install: {info['url']}")


def create_directories():
    """Create required directories."""
    print_step("Creating directories")
    dirs = [
        "screenshots",
        "voice_recordings",
        "exports/csv",
        "exports/parquet",
        "analytics",
        "config",
        "logs",
        "uploads",
    ]
    for d in dirs:
        (PROJECT_ROOT / d).mkdir(parents=True, exist_ok=True)
    print(f"  ✅ Created {len(dirs)} directories")


def init_database():
    """Initialize the SQLite database by running the backend once."""
    print_step("Database initialization")
    db_path = PROJECT_ROOT / "trading_journal.db"
    if db_path.exists():
        print(f"  ✅ Database exists ({db_path.stat().st_size / 1024:.0f} KB)")
        return

    # Try to start the backend briefly to create tables
    print("  Starting backend to initialize database...")
    try:
        subprocess.run(
            [sys.executable, str(PROJECT_ROOT / "backend" / "run.py")],
            cwd=str(PROJECT_ROOT),
            timeout=5,
        )
    except subprocess.TimeoutExpired:
        # The backend runs indefinitely — timeout is expected
        pass
    except Exception as e:
        print(f"  ⚠️  Could not auto-init database: {e}")
        print("  Run 'python backend/run.py' manually after setup")


