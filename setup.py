"""
Trading Journal With Voice — Setup / Install Script

Run this once to:
  1. Create .env from template if missing
  2. Install Python dependencies
  3. Check for external tools (Whisper.cpp, Ollama)
  4. Create necessary directories
  5. Initialize database (via backend)

Usage:
    python setup.py           # interactive setup
    python setup.py --quick   # quick setup (defaults only)
"""

import argparse
import os
import shutil
import subprocess
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent


def print_step(msg: str):
    print(f"\n{'='*60}")
    print(f"  {msg}")
    print(f"{'='*60}")


def check_python():
    """Check Python version."""
    print_step("Checking Python version")
    v = sys.version_info
    if v.major < 3 or (v.major == 3 and v.minor < 10):
        print(f"  ❌ Python 3.10+ required. You have {v.major}.{v.minor}.{v.micro}")
        return False
    print(f"  ✅ Python {v.major}.{v.minor}.{v.micro}")


def create_env():
    """Create .env file from template if it doesn't exist."""
    print_step("Environment configuration")
    env_path = PROJECT_ROOT / ".env"
    env_example = PROJECT_ROOT / "config" / ".env.example"

    if env_path.exists():
        print("  ✅ .env already exists")
        return

    # Create example env
    env_content = """# Trading Journal — Environment Variables
# Copy this to .env and fill in your keys

# --- Backend ---
DATABASE_URL=sqlite:///./trading_journal.db
CORS_ORIGINS=http://localhost:5173,http://localhost:3000

# --- Broker API Keys ---
# Alpaca (free stocks/crypto)
# ALPACA_API_KEY=
# ALPACA_SECRET_KEY=

# Interactive Brokers (requires TWS/Gateway running)
# IBKR_HOST=127.0.0.1
# IBKR_PORT=7497

# cTrader (free forex)
# CTRADER_CLIENT_ID=
# CTRADER_CLIENT_SECRET=

# Charles Schwab
# SCHWAB_APP_KEY=
# SCHWAB_APP_SECRET=

# --- AI ---
# Ollama runs locally (no key needed)
# OLLAMA_URL=http://localhost:11434

# Gemini API (free tier, 60 req/min)
# GEMINI_API_KEY=
"""
    if env_example.exists():
        shutil.copy2(env_example, env_path)
        print("  ✅ Created .env from config/.env.example")
    else:
        env_path.write_text(env_content)
        print("  ✅ Created .env with default values")
        print("  ⚠️  Edit .env to add your API keys")

    # Also create config/.env.example
    if not env_example.exists():
        env_example.parent.mkdir(parents=True, exist_ok=True)
        env_example.write_text(env_content)


