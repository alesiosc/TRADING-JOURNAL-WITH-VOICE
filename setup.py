def main():
    parser = argparse.ArgumentParser(description="Trading Journal Setup")
    parser.add_argument("--quick", action="store_true", help="Quick setup (skip optional checks)")
    args = parser.parse_args()

    print("""
  ╔══════════════════════════════════════════════╗
  ║    Trading Journal With Voice — Setup        ║
  ║    Free · Local-first · AI-powered           ║
  ╚══════════════════════════════════════════════╝
    """)

    check_python()
    create_env()
    create_directories()
    install_deps()

    if not args.quick:
        check_external_tools()

    init_database()
    print_summary()


if __name__ == "__main__":
    main()
